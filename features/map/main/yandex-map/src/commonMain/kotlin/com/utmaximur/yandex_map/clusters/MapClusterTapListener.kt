package com.utmaximur.yandex_map.clusters

import com.utmaximur.yandex_map.PlaceMarkIds

/**
 * Обработчик нажатий на кластеры карты, обеспечивающий управление слушателями и предотвращение утечек памяти.
 *
 * ### Особенности работы
 * 1. **Автоматическое управление слушателями**:
 *    Привязывает слушатели к кластерам и автоматически удаляет их при вызове [release].
 * 2. **Потокобезопасность**:
 *    Должен использоваться **только в основном потоке** (изменение коллекции кластеров в других потоках не поддерживается).
 * 3. **Фильтрация данных**:
 *    Извлекает только метки типа [PlaceMark], игнорируя другие объекты.
 *
 * ### Жизненный цикл
 * Обязательно вызывайте [release] при уничтожении компонента:
 */
internal expect class MapClusterTapListener(
    onClusterTap: ((PlaceMarkIds) -> Boolean)?
) {
    fun handle(cluster: MapCluster)
    fun release()
}