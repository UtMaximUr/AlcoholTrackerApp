package com.utmaximur.yandex_map.clusters

import com.utmaximur.yandex_map.resources.MapIconProvider

/**
 * Внутренний класс для оптимизированного обновления визуального представления кластеров на карте.
 *
 * Использует LRU-кэш для хранения сгенерированных иконок кластеров, чтобы избежать повторного создания
 * одинаковых представлений при частых обновлениях.
 *
 * ### Принцип работы
 * 1. При обновлении кластера определяется количество меток в нём (`cluster.placemarks.size`).
 * 2. Проверяется наличие готовой иконки в кэше:
 *    - Если иконка есть в кэше — используется кэшированная версия.
 *    - Если отсутствует — генерируется новая через [MapIcons.getClusterIcon] и сохраняется в кэш.
 * 3. Внешний вид кластера обновляется методом Cluster.appearance.setView.
 *
 * ### Особенности кэширования
 * - Размер кэша: 10 элементов (хранит иконки для 10 последних уникальных размеров кластеров).
 * - Стратегия вытеснения: Least Recently Used (удаляются реже всего используемые элементы).
 * - Кэш работает с "тяжёлыми" объектами ViewProvider, что экономит ресурсы на создании View.
 *
 * ### Ограничения
 * - Не потокобезопасен. Должен вызываться из основного потока.
 * - Размер кэша фиксирован. При частой смене размеров кластеров (>10 вариантов) возможны промахи кэша.
 *
 * @see LruCache
 */
internal expect class MapClusterViewUpdater(
    mapIconProvider: MapIconProvider
) {
    fun update(cluster: MapCluster)
}

