package com.utmaximur.yandex_map

import com.utmaximur.domain.models.Place

/**
 * Интерфейс для управления картой и её визуальными компонентами.
 * Обеспечивает базовые операции: добавление данных, управление отображением, обработку событий.
 */
internal interface AppMapController {

    /**
     * Радиус кластеризации объектов по умолчанию (в пикселях).
     * Используется для группировки близко расположенных объектов в кластеры.
     */
    val defaultClusterRadius get() = 42.0

    /**
     * Минимальный уровень зума, при котором происходит кластеризация.
     * При достижении этого значения объекты начинают группироваться.
     */
    val defaultMinZoom get() = 35

    /**
     * Оптимальный уровень зума для детального просмотра объектов.
     * Рекомендуется для отображения отдельных элементов без кластеризации.
     */
    val comfortableZoomLevel get() = 15f

    /**
     * Стандартный уровень зума для общего обзора.
     * Используется для отображения крупных областей с кластерами.
     */
    val commonZoomLevel get() = 10f

    /**
     * Обновляет данные на карте, заменяя текущий набор объектов.
     * @param places - Список объектов [Place] с геокоординатами и метаданными.
     * @throws IllegalArgumentException если список содержит некорректные координаты.
     */
    fun submitData(places: List<Place>)

    /**
     * Регистрирует обработчик кликов по объектам карты.
     * @param mapObjectListener - Лямбда, принимающая список ID объектов:
     * - Для одиночного объекта: список из одного элемента (ID объекта)
     * - Для кластера: список всех ID объектов в кластере
     */
    fun setMapObjectListener(mapObjectListener: (List<Long>) -> Unit)

    /**
     * Переключает карту в ночной/дневной режим.
     * @param isDarkMode - true для активации темной темы, false для светлой.
     */
    fun setDarkMode(isDarkMode: Boolean)

    /**
     * Метод жизненного цикла. Должен вызываться при старте связанного компонента.
     * Инициализирует ресурсы карты и подписки.
     */
    fun onStart()

    /**
     * Метод жизненного цикла. Должен вызываться при остановке связанного компонента.
     * Освобождает ресурсы карты и останавливает фоновые процессы.
     */
    fun onStop()
}